# Navegar a la carpeta del proyecto
Set-Location contactabilidad_inteligente.mcv

# Establecer entorno de desarrollo
$env:ASPNETCORE_ENVIRONMENT = "Development"

# Establecer entorno de producción
$env:ASPNETCORE_ENVIRONMENT = "Production"

# Establecer entorno local
$env:ASPNETCORE_ENVIRONMENT = "Local"

# ???????????????????????????????????????????????????????????????
# INFORMACIÓN DE DbContext
# ???????????????????????????????????????????????????????????????

# Ver información del DbContext
dotnet ef dbcontext info --context ApplicationDbContext

# Listar todas las migraciones
dotnet ef migrations list --context ApplicationDbContext

# Ver el estado actual de las migraciones
dotnet ef migrations list --context ApplicationDbContext --no-build

# ???????????????????????????????????????????????????????????????
# CREAR MIGRACIONES
# ???????????????????????????????????????????????????????????????

# Crear una nueva migración
dotnet ef migrations add NombreDeLaMigracion --context ApplicationDbContext

# Crear migración con salida específica
dotnet ef migrations add NombreDeLaMigracion --context ApplicationDbContext --output-dir Data/Migrations

# Crear migración forzando rebuild
dotnet ef migrations add NombreDeLaMigracion --context ApplicationDbContext --force

# ???????????????????????????????????????????????????????????????
# APLICAR MIGRACIONES (SOLO DESARROLLO/LOCAL)
# ???????????????????????????????????????????????????????????????

# ?? NUNCA usar en producción
# Aplicar todas las migraciones pendientes
dotnet ef database update --context ApplicationDbContext

# Aplicar hasta una migración específica
dotnet ef database update NombreMigracion --context ApplicationDbContext

# Revertir todas las migraciones (volver a estado inicial)
dotnet ef database update 0 --context ApplicationDbContext

# ???????????????????????????????????????????????????????????????
# GENERAR SCRIPTS SQL (PARA PRODUCCIÓN)
# ???????????????????????????????????????????????????????????????

# Script completo idempotente (desde el inicio)
dotnet ef migrations script --context ApplicationDbContext `
    --output ".\Data\Migrations\Scripts\Prod_Full_$(Get-Date -Format 'yyyyMMdd_HHmmss').sql" `
    --idempotent

# Script incremental (desde una migración hasta otra)
dotnet ef migrations script MigracionOrigen MigracionDestino --context ApplicationDbContext `
    --output ".\Data\Migrations\Scripts\Prod_Incremental_$(Get-Date -Format 'yyyyMMdd_HHmmss').sql" `
    --idempotent

# Script de la última migración solamente
dotnet ef migrations script PenultimaMigracion UltimaMigracion --context ApplicationDbContext `
    --output ".\Data\Migrations\Scripts\Prod_Last_$(Get-Date -Format 'yyyyMMdd_HHmmss').sql" `
    --idempotent

# Script sin opción idempotent (no recomendado para producción)
dotnet ef migrations script --context ApplicationDbContext `
    --output ".\Data\Migrations\Scripts\Dev_Script.sql"

# ???????????????????????????????????????????????????????????????
# ELIMINAR MIGRACIONES
# ???????????????????????????????????????????????????????????????

# Eliminar la última migración (si NO se ha aplicado)
dotnet ef migrations remove --context ApplicationDbContext

# Eliminar la última migración forzadamente
dotnet ef migrations remove --context ApplicationDbContext --force

# ???????????????????????????????????????????????????????????????
# RECREAR BASE DE DATOS (SOLO DESARROLLO)
# ???????????????????????????????????????????????????????????????

# ?? PELIGRO: Elimina y recrea la base de datos
dotnet ef database drop --context ApplicationDbContext --force
dotnet ef database update --context ApplicationDbContext

# ???????????????????????????????????????????????????????????????
# SCRIPTS PERSONALIZADOS DEL PROYECTO
