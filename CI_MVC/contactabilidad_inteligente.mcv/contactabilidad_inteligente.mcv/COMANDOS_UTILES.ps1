# COMANDOS SQL ÚTILES (Ejecutar en SSMS)
# ???????????????????????????????????????????????????????????????

<#
-- Ver migraciones aplicadas
SELECT * FROM [__EFMigrationsHistory] ORDER BY MigrationId DESC;

-- Ver tablas del esquema
SELECT TABLE_SCHEMA, TABLE_NAME 
FROM INFORMATION_SCHEMA.TABLES 
WHERE TABLE_TYPE = 'BASE TABLE'
ORDER BY TABLE_SCHEMA, TABLE_NAME;

-- Ver permisos del usuario
SELECT 
    dp.name AS UserName,
    dp.type_desc AS UserType,
    o.name AS ObjectName,
    p.permission_name,
    p.state_desc
FROM sys.database_permissions p
    INNER JOIN sys.database_principals dp ON p.grantee_principal_id = dp.principal_id
    LEFT JOIN sys.objects o ON p.major_id = o.object_id
WHERE dp.name = 'BANCOMACHALA\pedro.rivera'
ORDER BY ObjectName, permission_name;

-- Insertar migración manualmente (después de ejecutar script SQL en producción)
INSERT INTO [__EFMigrationsHistory] ([MigrationId], [ProductVersion])
VALUES (N'20250124123456_NombreDeLaMigracion', N'9.0.9');
