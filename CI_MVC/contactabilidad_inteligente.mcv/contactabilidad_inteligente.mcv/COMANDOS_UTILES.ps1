.\Generate-MigrationScript.ps1 -ListMigrations

# Generar script completo
.\Generate-MigrationScript.ps1 -FullScript

# Generar script de una migración específica
.\Generate-MigrationScript.ps1 -MigrationName "AgregarTablaCampania"

# Generar script incremental
.\Generate-MigrationScript.ps1 -MigrationName "MigracionDestino" -FromMigration "MigracionOrigen"

